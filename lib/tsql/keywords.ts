export function formatKeyword(word: string, keywordCase: KeywordCase): string {
  if (!TSQL_KEYWORDS.has(word.toLowerCase())) {
    return word
  }

  return keywordCase === "upper" ? word.toUpperCase() : word.toLowerCase()
}
